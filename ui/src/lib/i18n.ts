const extra: Record<string, Dict> = { fr: {}, en: {} };

/** Permet aux mods d'ajouter ou de remplacer des chaînes. */
export function registerStrings(lang: 'fr' | 'en', strings: Dict) {
  Object.assign(extra[lang], strings);
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const lang = prefs.lang;
  const table = lang === 'en' ? en : fr;
  let s = extra[lang][key] ?? table[key] ?? fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function tileDesc(id: string, fallback: string): string {
  return prefs.lang === 'en' ? (descEn[id] ?? fallback) : fallback;
}

